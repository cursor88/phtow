async function insertFoodHerbs() {
  console.log('\n========== 添加药食同源药材 ==========')
  console.log(`待添加药材数量: ${missingFoodHerbs.length}`)

  let conn
  try {
    conn = await pool.getConnection()
    await conn.beginTransaction()

    let successCount = 0
    let failCount = 0

    for (const herb of missingFoodHerbs) {
      try {
        await conn.query(
          `INSERT INTO herbs (id, name, pinyin, alias, category, nature, taste, meridian, effect, indication, dosage, taboo, identify_points, image_type, keywords, is_food_medicine)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
           ON DUPLICATE KEY UPDATE
             name = VALUES(name),
             pinyin = VALUES(pinyin),
             alias = VALUES(alias),
             category = VALUES(category),
             nature = VALUES(nature),
             taste = VALUES(taste),
             meridian = VALUES(meridian),
             effect = VALUES(effect),
             indication = VALUES(indication),
             dosage = VALUES(dosage),
             taboo = VALUES(taboo),
             identify_points = VALUES(identify_points),
             image_type = VALUES(image_type),
             keywords = VALUES(keywords),
             is_food_medicine = VALUES(is_food_medicine)`,
          [
            herb.id,
            herb.name,
            herb.pinyin,
            JSON.stringify(herb.alias),
            herb.category,
            herb.nature,
            herb.taste,
            herb.meridian,
            herb.effect,
            herb.indication,
            herb.dosage,
            herb.taboo,
            herb.identify_points,
            herb.image_type,
            herb.keywords,
            1
          ]
        )

        console.log(`  ✓ ${herb.id}. ${herb.name}`)
        successCount++
      } catch (error) {
        failCount++
        console.error(`  ✗ ${herb.name}: ${error.message}`)
      }
    }

    await conn.commit()
    console.log('\n========== 添加完成 ==========')
    console.log(`成功: ${successCount} 条`)
    console.log(`失败: ${failCount} 条`)

  } catch (error) {
    if (conn) await conn.rollback()
    console.error('添加失败:', error.message)
    throw error
  } finally {
    if (conn) conn.release()
    await pool.end()
  }
}

insertFoodHerbs().catch(console.error)